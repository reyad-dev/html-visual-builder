import { sanitizeHtml } from './sanitizeHtml';
import type { ExportOptions } from './types';

/**
 * Escapes characters that are special in HTML attributes or text content.
 * Prevents HTML/XSS injection through title, metadata, or language fields.
 */
export function escapeHtml(str: string): string {
  if (!str || typeof str !== 'string') {
    return '';
  }
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * Scans HTML content and identifies any remote URLs (http, https, protocol-relative)
 * referenced in src or href attributes (e.g. remote images, stylesheets, or links).
 */
export function detectRemoteAssets(html: string): string[] {
  if (!html || typeof html !== 'string') {
    return [];
  }
  const urls = new Set<string>();
  const regex = /(?:src|href)\s*=\s*["']((?:https?:|\/\/)[^"']+)["']/gi;
  let match: RegExpExecArray | null;

  while ((match = regex.exec(html)) !== null) {
    if (match[1]) {
      urls.add(match[1]);
    }
  }

  return Array.from(urls);
}

/**
 * Generates a complete, deterministic, standalone HTML5 document.
 * Safely includes doctype, head, metadata, style block, and sanitized body content.
 */
export function exportStandaloneHtml(options: ExportOptions): string {
  const lang = escapeHtml(options.lang?.trim() || 'en');
  const title = escapeHtml(options.title?.trim() || 'Exported Document');

  // Sanitize body HTML to guarantee no executable scripts or event handlers exist
  const rawBody = options.bodyHtml || '';
  const sanitizedResult = sanitizeHtml(rawBody);
  let cleanBody = sanitizedResult.cleanHtml.trim();

  // Strip any accidental javascript: URL schemes that might persist
  cleanBody = cleanBody.replace(/(?:href|src)\s*=\s*["']\s*javascript:[^"']*["']/gi, 'href="#"');

  // Build meta tags safely
  const metaLines: string[] = [
    '    <meta charset="utf-8">',
    '    <meta name="viewport" content="width=device-width, initial-scale=1">',
    `    <title>${title}</title>`,
  ];

  if (options.meta && Array.isArray(options.meta)) {
    for (const m of options.meta) {
      if (m.name) {
        metaLines.push(
          `    <meta name="${escapeHtml(m.name)}" content="${escapeHtml(m.content)}">`
        );
      } else if (m.property) {
        metaLines.push(
          `    <meta property="${escapeHtml(m.property)}" content="${escapeHtml(m.content)}">`
        );
      }
    }
  }

  if (options.externalStylesheets && Array.isArray(options.externalStylesheets)) {
    for (const href of options.externalStylesheets) {
      if (href && !href.trim().toLowerCase().startsWith('javascript:')) {
        metaLines.push(`    <link rel="stylesheet" href="${escapeHtml(href.trim())}">`);
      }
    }
  }

  // Sanitize CSS to prevent style element breakout
  const safeCss = (options.css || '').replace(/<\/style/gi, '<\\/style').trim();

  return `<!doctype html>
<html lang="${lang}">
  <head>
${metaLines.join('\n')}
    <style>
${safeCss ? safeCss : '/* Generated by HTML Visual Builder */'}
    </style>
  </head>
  <body>
${cleanBody}
  </body>
</html>`;
}

/**
 * Triggers a client-side download of the HTML content as a standalone file.
 */
export function downloadHtmlFile(content: string, filename = 'exported-page.html'): void {
  if (typeof document === 'undefined' || typeof window === 'undefined') {
    return;
  }

  const cleanFilename = filename.endsWith('.html') || filename.endsWith('.htm')
    ? filename
    : `${filename}.html`;

  const blob = new Blob([content], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = cleanFilename;
  anchor.style.display = 'none';

  document.body.appendChild(anchor);
  anchor.click();

  setTimeout(() => {
    if (document.body.contains(anchor)) {
      document.body.removeChild(anchor);
    }
    URL.revokeObjectURL(url);
  }, 1000);
}

/**
 * Copies plain text to the user's system clipboard with modern API and fallback support.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  if (typeof navigator !== 'undefined' && navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fall through to fallback
    }
  }

  if (typeof document !== 'undefined') {
    try {
      const textarea = document.createElement('textarea');
      textarea.value = text;
      textarea.setAttribute('readonly', '');
      textarea.style.position = 'fixed';
      textarea.style.left = '-9999px';
      textarea.style.top = '-9999px';
      document.body.appendChild(textarea);
      textarea.select();
      const success = document.execCommand('copy');
      document.body.removeChild(textarea);
      return Boolean(success);
    } catch {
      return false;
    }
  }

  return false;
}

/**
 * Triggers a high-fidelity print / PDF export dialog for the given HTML document.
 * Creates an isolated iframe, loads Google Fonts & styles, and triggers window.print().
 */
export function printDocument(options: {
  title?: string;
  bodyHtml: string;
  css: string;
  externalStylesheets?: string[];
}): void {
  if (typeof document === 'undefined' || typeof window === 'undefined') {
    return;
  }

  const title = options.title || 'Document';
  const fullHtml = exportStandaloneHtml({
    title,
    bodyHtml: options.bodyHtml,
    css: `
      @media print {
        @page {
          margin: 1.5cm;
          size: auto;
        }
        body {
          -webkit-print-color-adjust: exact !important;
          print-color-adjust: exact !important;
        }
      }
      ${options.css || ''}
    `,
    externalStylesheets: [
      'https://fonts.googleapis.com/css2?family=Alexandria:wght@300;400;500;600;700&family=Cairo:wght@400;500;600;700&family=Inter:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;500;600&family=Tajawal:wght@400;500;700&display=swap',
      ...(options.externalStylesheets || []),
    ],
  });

  const iframe = document.createElement('iframe');
  iframe.style.position = 'fixed';
  iframe.style.right = '0';
  iframe.style.bottom = '0';
  iframe.style.width = '0';
  iframe.style.height = '0';
  iframe.style.border = '0';
  iframe.setAttribute('aria-hidden', 'true');
  iframe.setAttribute('title', 'Print Preview Frame');

  document.body.appendChild(iframe);

  const doc = iframe.contentWindow?.document || iframe.contentDocument;
  if (!doc) {
    return;
  }

  doc.open();
  doc.write(fullHtml);
  doc.close();

  // Wait briefly for styles and fonts to paint before triggering print dialog
  setTimeout(() => {
    try {
      iframe.contentWindow?.focus();
      iframe.contentWindow?.print();
    } catch {
      window.print();
    } finally {
      setTimeout(() => {
        if (document.body.contains(iframe)) {
          document.body.removeChild(iframe);
        }
      }, 2000);
    }
  }, 350);
}
